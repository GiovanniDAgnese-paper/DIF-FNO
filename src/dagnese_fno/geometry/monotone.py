"""The D'Agnese Triangular Monotone Chart: a globally injective, exactly
invertible, resolution-independent diffeomorphism of the reference square.

Motivation
----------
The certificate of DIF-FNO v1 (:func:`dagnese_fno.geometry.certified_det_lower_bound`)
is *local*: it bounds :math:`\\det J_\\phi` pointwise through a Lipschitz
constant, which (i) forces :math:`\\kappa L < 1` -- for pointwise conditioning
that means :math:`L < 3\\cdot10^{-3}`, i.e. an infinitesimal perturbation of the
identity -- and (ii) does not imply that :math:`\\phi` is injective, only that it
is a local diffeomorphism.  The v1 documentation says so itself.

This module removes the gap with a *constructive* class.

Definition (D'Agnese chart)
---------------------------
In normalised coordinates :math:`u, v \\in [0,1]`,

.. math::
    \\Phi(u, v) = \\big(g(u),\\; h(u, v)\\big),

where :math:`g` is continuous, piecewise linear, strictly increasing with
:math:`g(0)=0, g(1)=1`, and :math:`h(u,\\cdot)` is, for every :math:`u`,
strictly increasing with :math:`h(u,0)=0, h(u,1)=1`; :math:`h` is piecewise
bilinear with :math:`h(\\cdot,v)` linear between the rows.

Both are generated by *strictly positive* increments -- a softmax of
unconstrained logits.  Positivity is therefore structural: a finite logit can
never produce a zero increment or a sign flip (a softplus of a large negative
number underflows to zero, and a zero increment folds the grid).

Proposition P5 (D'Agnese global certificate)
--------------------------------------------
**(i) Global injectivity.**  If :math:`\\Phi(u,v)=\\Phi(u',v')` then
:math:`g(u)=g(u')`, and :math:`g` strictly increasing gives :math:`u=u'`; then
:math:`h(u,v)=h(u,v')` and :math:`h(u,\\cdot)` strictly increasing gives
:math:`v=v'`.  So :math:`\\Phi` is injective on the whole square: no
local-to-global gap.

**(ii) Orientation.**  On each cell the Jacobian is *lower triangular*,

.. math::
    J_\\Phi = \\begin{pmatrix} g' & 0 \\\\ \\partial_u h & \\partial_v h
    \\end{pmatrix},
    \\qquad \\det J_\\Phi = g' \\,\\partial_v h > 0 ,

a product of two strictly positive numbers.  It is computed as a product, never
as :math:`ad-bc`, so the sign cannot be destroyed by cancellation.

**(iii) Exact inverse.**  :math:`\\Phi^{-1}(y_1,y_2) = (g^{-1}(y_1),
h(g^{-1}(y_1),\\cdot)^{-1}(y_2))`: two monotone 1-D inversions in closed form.

**(iv) No size restriction.**  Arbitrarily large deformations are admissible;
the certified lower bound :math:`\\min_i \\Delta g_i \\cdot \\min_{ij}\\Delta h_{ij}
> 0` is finite for every parameter value.  It does not degrade as the
deformation grows -- unlike :math:`(1-\\kappa L)^2`, which vanishes as the
deformation reaches the identity's Lipschitz neighbourhood.

**(v) Identity at initialisation.**  A zero output layer gives constant logits,
a uniform softmax and :math:`\\Phi=\\mathrm{Id}` exactly.

**(vi) Closure under composition.**  ``n_layers > 1`` composes charts; each
composition is injective and orientation preserving, and the second layer is
evaluated at the points of the first by bilinear interpolation, which *is* the
piecewise-bilinear map it represents.

The class contains the identity and is closed under composition: it is a monoid
of admissible charts, not a neighbourhood of the identity.
"""

from __future__ import annotations

import math

import torch
import torch.nn as nn

from .jacobian import jacobian_det

__all__ = ["DagneseTriangularChart", "invert_monotone_1d", "chart_det_consistency"]


# --------------------------------------------------------------------------- #
# Monotone 1-D inversion
# --------------------------------------------------------------------------- #
def _bracket(seq: torch.Tensor, values: torch.Tensor) -> torch.Tensor:
    """Index ``i`` with ``seq[i] <= values < seq[i+1]`` (``seq`` strictly increasing).

    ``seq``    : ``(B, K)``
    ``values`` : ``(B, M)``

    Vectorised binary search: ``O(log K)`` gathers, no expansion of the knot
    tensor, and ``O(B*M)`` memory -- the alternative
    (``torch.searchsorted`` on a broadcast sequence) would materialise
    ``B*M*K`` floats, i.e. 0.5 GB for a batch of 64x64 grids.
    """
    if seq.dim() != 2 or values.dim() != 2:
        raise ValueError("_bracket expects (B, K) and (B, M)")
    if seq.shape[0] != values.shape[0]:
        raise ValueError("batch mismatch in _bracket")
    k = seq.shape[-1]
    steps = int(math.ceil(math.log2(k))) + 1
    lo = torch.zeros_like(values, dtype=torch.long)
    hi = torch.full_like(values, k - 1, dtype=torch.long)
    for _ in range(steps):
        mid = (lo + hi) // 2
        at_mid = torch.gather(seq, 1, mid.clamp(0, k - 1))
        below = at_mid <= values
        lo = torch.where(below, mid, lo)
        hi = torch.where(below, hi, mid)
        hi = torch.maximum(hi, lo + 1)
    return lo.clamp(0, k - 2)


def invert_monotone_1d(knots: torch.Tensor, values: torch.Tensor
                       ) -> tuple[torch.Tensor, torch.Tensor]:
    """Invert a strictly increasing piecewise-linear map.

    ``knots``  : ``(B, K)`` increasing values (images of a uniform grid)
    ``values`` : ``(B, M)`` targets

    Returns ``(position, frac)``: the continuous index in ``[0, K-1]`` and the
    interpolation weight inside the bracket.  Differentiable with respect to
    ``knots`` almost everywhere (the bracket is piecewise constant, the weight
    carries the gradient).
    """
    if knots.dim() != 2 or values.dim() != 2:
        raise ValueError("invert_monotone_1d expects (B, K) and (B, M)")
    if knots.shape[-1] < 2:
        raise ValueError("need at least two knots")
    if knots.shape[0] != values.shape[0]:
        raise ValueError("batch mismatch between knots and values")
    idx = _bracket(knots, values)
    lo = torch.gather(knots, 1, idx)
    hi = torch.gather(knots, 1, idx + 1)
    span = (hi - lo).clamp_min(torch.finfo(knots.dtype).tiny)
    frac = ((values - lo) / span).clamp(0.0, 1.0)
    return idx.to(values.dtype) + frac, frac


class DagneseTriangularChart(nn.Module):
    """A certified chart :math:`\\Phi(u,v) = (g(u), h(u,v))` on the reference square.

    Parameters
    ----------
    hidden:
        Width of the logit-field network.
    n_layers:
        Number of composed triangular charts (one is already globally injective
        and orientation preserving; more layers increase expressivity).
    latent_dim:
        Dimension of the per-sample code. ``0`` gives a single chart shared by
        every sample (a *learned adaptive mesh*); ``> 0`` gives a family of
        charts (a *learned mesh model*).
    n_fourier:
        Fourier features per axis for the logit field. The chart can only move
        nodes smoothly, so this controls the spatial richness of the mesh.
    identity_init:
        Zero-initialise the last layer, so :math:`\\Phi = \\mathrm{Id}` at
        ``t = 0`` (P5.v).
    """

    def __init__(
        self,
        hidden: int = 32,
        n_layers: int = 1,
        latent_dim: int = 0,
        n_fourier: int = 3,
        activation: str = "tanh",
        identity_init: bool = True,
        min_increment: float = 1e-3,
    ) -> None:
        super().__init__()
        if n_layers < 1:
            raise ValueError("n_layers must be >= 1")
        self.hidden = int(hidden)
        self.n_layers = int(n_layers)
        self.latent_dim = int(latent_dim)
        self.n_fourier = int(n_fourier)
        self.activation = activation
        self.identity_init = bool(identity_init)
        if not 0.0 <= float(min_increment) < 1.0:
            raise ValueError("min_increment must lie in [0, 1)")
        self.min_increment = float(min_increment)

        n_feat = 2 + 4 * self.n_fourier + self.latent_dim
        act = {"tanh": nn.Tanh, "silu": nn.SiLU, "gelu": nn.GELU, "softplus": nn.Softplus}
        if activation not in act:
            raise ValueError(f"unknown activation '{activation}'; available: {sorted(act)}")

        self.nets = nn.ModuleList()
        for _ in range(self.n_layers):
            net = nn.Sequential(
                nn.Linear(n_feat, hidden),
                act[activation](),
                nn.Linear(hidden, hidden),
                act[activation](),
                nn.Linear(hidden, 2),
            )
            if identity_init:
                nn.init.zeros_(net[-1].weight)
                nn.init.zeros_(net[-1].bias)
            self.nets.append(net)

    # ------------------------------------------------------------------ #
    # Features and knots
    # ------------------------------------------------------------------ #
    def _align(self, coords: torch.Tensor, code: torch.Tensor | None) -> torch.Tensor:
        """Broadcast an unbatched grid against a batched code (and vice versa)."""
        if self.latent_dim == 0 or code is None:
            return coords
        if code.dim() == 1:
            code_shape = (1,)
        else:
            code_shape = code.shape[:-1]
        if coords.dim() == 3 and len(code_shape) == 1:
            if code_shape[0] not in (1,):
                coords = coords.unsqueeze(0).expand(code_shape[0], *coords.shape)
        return coords

    def _features(self, coords: torch.Tensor, code: torch.Tensor | None = None) -> torch.Tensor:
        coords = self._align(coords, code)
        u = (coords[..., 0] + 1.0) * 0.5
        v = (coords[..., 1] + 1.0) * 0.5
        feats = [u.unsqueeze(-1), v.unsqueeze(-1)]
        for k in range(1, self.n_fourier + 1):
            feats.append(torch.sin(math.pi * k * u).unsqueeze(-1))
            feats.append(torch.cos(math.pi * k * u).unsqueeze(-1))
            feats.append(torch.sin(math.pi * k * v).unsqueeze(-1))
            feats.append(torch.cos(math.pi * k * v).unsqueeze(-1))
        if self.latent_dim > 0:
            if code is None:
                raise ValueError("this chart has latent_dim > 0: a code is required")
            if code.shape[-1] != self.latent_dim:
                raise ValueError(f"code must have last dim {self.latent_dim}, got {code.shape[-1]}")
            n_batch = code.dim() - 1
            c = code.reshape(*code.shape[:n_batch], *([1] * (coords.dim() - 1 - n_batch)),
                             self.latent_dim)
            feats.append(c.expand(*coords.shape[:-1], self.latent_dim))
        return torch.cat(feats, dim=-1)

    @staticmethod
    def _cumulative(weights: torch.Tensor) -> torch.Tensor:
        """Positive increments with total 1 -> knots in ``[0, 1]`` (``K+1`` knots)."""
        zero = torch.zeros_like(weights[..., :1])
        return torch.cat([zero, torch.cumsum(weights, dim=-1)], dim=-1)

    def _knots(self, coords: torch.Tensor, code: torch.Tensor | None, layer: int
               ) -> tuple[torch.Tensor, torch.Tensor]:
        """Row knots ``g`` ``(..., N)`` and column knots ``h`` ``(..., N, N)``."""
        logits = self.nets[layer](self._features(coords, code))
        n = coords.shape[-2]
        row_logits = logits[..., 0].mean(dim=-1)                      # (..., N)
        col_logits = logits[..., 1]                                   # (..., N, N)
        g_inc = self._positive(row_logits[..., :-1])                  # (..., N-1)
        h_inc = self._positive(col_logits[..., :-1])                  # (..., N, N-1)
        return self._cumulative(g_inc), self._cumulative(h_inc)

    def _positive(self, logits: torch.Tensor) -> torch.Tensor:
        r"""Strictly positive increments summing to one, with a *floating-point* floor.

        A pure softmax is strictly positive in exact arithmetic but underflows to
        exactly ``0`` in float32 once the logits span more than ~90.  A zero
        increment is a folded cell, so an adversarial parameter value could
        silently destroy the guarantee.  The mixture

        .. math:: w = (1-\varepsilon)\,\mathrm{softmax}(z) + \varepsilon / K

        is strictly positive for every finite ``z``, it is *exactly* uniform when
        ``z`` is constant -- so identity initialisation is preserved to the last
        bit -- and it yields the parameter-free bound ``w_i >= eps/K``.

        The default ``eps = 1e-3`` is chosen so that the bound survives
        *floating point*: with ``K = 63`` every increment is at least
        ``1.6e-5``, i.e. ~256 ulps at 1.0, so the cumulative sum that produces
        the knots cannot absorb an increment and cannot produce a repeated knot.
        A smaller ``eps`` (say ``1e-8``) is mathematically fine but numerically
        useless: the cumsum rounds the tiny increments away and the "strictly
        increasing" knots come back as a constant run -- a folded cell created by
        the arithmetic, not by the model.  The bias it introduces is a cap of
        ``K/eps ~ 6e4`` on the cell-size ratio of the mesh, far outside anything a
        learned chart needs.
        """
        k = logits.shape[-1]
        p = torch.softmax(logits, dim=-1)
        eps = self.min_increment
        if eps <= 0.0:
            return p
        return (1.0 - eps) * p + eps / k

    # ------------------------------------------------------------------ #
    # One layer: exact piecewise-bilinear evaluation and its Jacobian
    # ------------------------------------------------------------------ #
    def _apply_layer(self, knots: tuple[torch.Tensor, torch.Tensor],
                     points: torch.Tensor) -> torch.Tensor:
        """Evaluate one layer at arbitrary ``points`` (exact piecewise bilinear).

        The map is evaluated by two gathers: the first coordinate depends on the
        row position only, the second is bilinear in the position.  Knot arrays
        are broadcast to ``(..., N, N, N)`` (position row, position column, knot)
        -- 1 MB per sample at ``N = 64``.
        """
        g, h = knots
        n = g.shape[-1]
        lead = points.shape[:-1]                       # (..., N, N): positions
        u = ((points[..., 0] + 1.0) * 0.5).clamp(0.0, 1.0)
        v = ((points[..., 1] + 1.0) * 0.5).clamp(0.0, 1.0)

        x = u * (n - 1)
        i = x.floor().clamp(0, n - 2).long()
        t = x - i.to(x.dtype)

        g_b = g.reshape(*g.shape[:-1], 1, 1, n).expand(*lead, n)
        g0 = torch.gather(g_b, -1, i.unsqueeze(-1)).squeeze(-1)
        g1 = torch.gather(g_b, -1, (i + 1).unsqueeze(-1)).squeeze(-1)
        g_out = g0 * (1 - t) + g1 * t

        h_b = h.reshape(*h.shape[:-2], 1, n, n).expand(*lead, n)
        idx = i.unsqueeze(-1).expand(*lead, n)
        h_lo = torch.gather(h_b, -2, idx)
        h_hi = torch.gather(h_b, -2, idx + 1)
        h_row = h_lo * (1 - t).unsqueeze(-1) + h_hi * t.unsqueeze(-1)

        y = v * (n - 1)
        j = y.floor().clamp(0, n - 2).long()
        s = y - j.to(y.dtype)
        h0 = torch.gather(h_row, -1, j.unsqueeze(-1)).squeeze(-1)
        h1 = torch.gather(h_row, -1, (j + 1).unsqueeze(-1)).squeeze(-1)
        h_out = h0 * (1 - s) + h1 * s

        return torch.stack([g_out * 2.0 - 1.0, h_out * 2.0 - 1.0], dim=-1)

    @staticmethod
    def _det_from_knots(n: int, g: torch.Tensor, h: torch.Tensor) -> torch.Tensor:
        """Nodal ``det J`` of a layer with the *symmetric* stencil of ``jacobian_det``.

        Kept for diagnostics and for compatibility with the smooth-diffeomorphism
        path.  Note what it is: the derivative of a piecewise-linear map jumps at
        the nodes, so a symmetric stencil returns the *arithmetic mean* of the
        two one-sided slopes.  On a violently oscillating mesh that mean can be
        negative even though both slopes are positive -- which is why this
        quantity is **not** used by the certificate (``forward`` returns the exact
        cell-wise determinant instead, and ``_det_layer_at`` is a product of
        positive increments for every parameter value).

        ``phi_1 = 2g - 1`` depends on :math:`\\xi_1 = 2u-1` only, and
        ``phi_2 = 2h - 1``; with :math:`\\Delta\\xi = 2/(n-1)` the two diagonal
        entries of :math:`J_\\Phi` are :math:`2\\Delta g/\\Delta\\xi` and
        :math:`2\\Delta h/\\Delta\\xi`, both strictly positive.
        """
        h_phys = 2.0 / (n - 1)
        # Central differences in the interior, second-order one-sided at the
        # boundary: exactly the stencil of jacobian_det, so the two determinants
        # agree to machine precision (a regression test).
        dg = torch.zeros_like(g)
        dg[..., 1:-1] = (g[..., 2:] - g[..., :-2]) / (2.0 * h_phys)
        dg[..., 0] = (-3.0 * g[..., 0] + 4.0 * g[..., 1] - g[..., 2]) / (2.0 * h_phys)
        dg[..., -1] = (3.0 * g[..., -1] - 4.0 * g[..., -2] + g[..., -3]) / (2.0 * h_phys)
        dh = torch.zeros_like(h)
        dh[..., :, 1:-1] = (h[..., :, 2:] - h[..., :, :-2]) / (2.0 * h_phys)
        dh[..., :, 0] = (-3.0 * h[..., :, 0] + 4.0 * h[..., :, 1] - h[..., :, 2]) / (2.0 * h_phys)
        dh[..., :, -1] = (3.0 * h[..., :, -1] - 4.0 * h[..., :, -2] + h[..., :, -3]) / (2.0 * h_phys)
        return (2.0 * dg).unsqueeze(-1) * (2.0 * dh)

    # ------------------------------------------------------------------ #
    # Public API
    # ------------------------------------------------------------------ #
    def forward(self, coords: torch.Tensor, code: torch.Tensor | None = None
                ) -> tuple[torch.Tensor, torch.Tensor]:
        """Map reference nodes to the chart.

        Returns ``(phi, det_j)``.  The knots of every layer are computed on the
        **reference** grid, so the composed map is a well-defined function of
        the reference coordinates and its inverse is exact; the layers
        themselves are evaluated by exact piecewise-bilinear interpolation at
        the intermediate images.
        """
        if coords.shape[-1] != 2:
            raise ValueError(f"coords must have last dimension 2, got {coords.shape[-1]}")
        coords = self._align(coords, code)
        n = coords.shape[-2]
        points = coords
        total = torch.ones(coords.shape[:-1], device=coords.device, dtype=coords.dtype)
        for layer in range(self.n_layers):
            g, h = self._knots(coords, code, layer)
            total = total * self._det_layer_at((g, h), points)
            points = self._apply_layer((g, h), points)
        return points, total

    def _det_layer_at(self, knots: tuple[torch.Tensor, torch.Tensor],
                      points: torch.Tensor) -> torch.Tensor:
        """Exact ``det J`` of one layer at arbitrary ``points`` (cell-wise formula).

        On the cell ``(i, j)`` the map is bilinear, so

        .. math::
            det J = (2 dg_i / dxi) * (2 [(1-t) dv h_ij + t dv h_{i+1,j}] / dxi) > 0

        with :math:`t` the fractional row position: a product of positive
        increments, so positivity holds at every point of the square, not only at
        the nodes.  The computation is done on flat arrays to keep the memory at
        ``O(B N^2)`` instead of ``O(B N^4)``.
        """
        g, h = knots
        n = g.shape[-1]
        n2 = n * n
        lead = points.shape[:-1]
        b = points.numel() // (n2 * 2)
        h_phys = 2.0 / (n - 1)

        u = ((points[..., 0] + 1.0) * 0.5).clamp(0.0, 1.0).reshape(b, n2)
        v = ((points[..., 1] + 1.0) * 0.5).clamp(0.0, 1.0).reshape(b, n2)
        x = u * (n - 1)
        i = x.floor().clamp(0, n - 2).long()
        t = x - i.to(x.dtype)
        j = (v * (n - 1)).floor().clamp(0, n - 2).long()

        dg = torch.diff(g, dim=-1).reshape(b, n - 1)
        dg_i = torch.gather(dg, 1, i)

        dh = torch.diff(h, dim=-1).reshape(b, n * (n - 1))
        flat_lo = i * (n - 1) + j
        dh_lo = torch.gather(dh, 1, flat_lo)
        dh_hi = torch.gather(dh, 1, flat_lo + (n - 1))
        dh_row = dh_lo * (1 - t) + dh_hi * t

        det = (2.0 * dg_i / h_phys) * (2.0 * dh_row / h_phys)
        return det.reshape(*lead)

    def inverse(self, points: torch.Tensor, code: torch.Tensor | None = None,
                reference: torch.Tensor | None = None) -> torch.Tensor:
        """Exact inverse of the chart at ``points``.

        ``reference`` is the grid the chart was discretised on (defaults to the
        canonical grid with the same resolution as ``points``).  The inverse of
        a composition is the composition of the inverses, in reverse order.
        """
        n = points.shape[-2]
        lead = points.shape[:-3]
        flat = points.reshape(-1, n, n, 2)
        if reference is None:
            reference = self._reference_grid(n, points.device, points.dtype)
        reference = self._align(reference, code)
        b = flat.shape[0]
        for layer in reversed(range(self.n_layers)):
            g, h = self._knots(reference, code, layer)
            g2 = g.reshape(-1, n)
            h2 = h.reshape(-1, n, n)
            if g2.shape[0] != b:
                g2 = g2.expand(b, n)
                h2 = h2.expand(b, n, n)
            flat = self._invert_layer((g2, h2), flat)
        return flat.reshape(*lead, n, n, 2)

    @staticmethod
    def _invert_layer(knots: tuple[torch.Tensor, torch.Tensor],
                      points: torch.Tensor) -> torch.Tensor:
        """Invert one layer; ``points`` is ``(B, N, N, 2)``."""
        g, h = knots
        b, n = g.shape[0], g.shape[-1]
        y1 = (points[..., 0] + 1.0) * 0.5
        y2 = (points[..., 1] + 1.0) * 0.5

        pos_u, _ = invert_monotone_1d(g, y1.reshape(b, -1))
        pos_u = pos_u.reshape(b, n, n)
        u = pos_u / (n - 1)

        i = pos_u.floor().clamp(0, n - 2).long()
        t = (pos_u - i.floor().to(pos_u.dtype)).unsqueeze(-1)
        h_flat = h.reshape(b, n, n)
        h_lo = torch.gather(h_flat, 1, i.reshape(b, -1).unsqueeze(-1).expand(b, n * n, n))
        h_hi = torch.gather(h_flat, 1, (i + 1).reshape(b, -1).unsqueeze(-1).expand(b, n * n, n))
        h_row = (h_lo * (1 - t.reshape(b, -1, 1)) + h_hi * t.reshape(b, -1, 1))  # (B, N*N, N)

        m = n * n
        pos_v, _ = invert_monotone_1d(h_row.reshape(b * m, n), y2.reshape(b * m, 1))
        v = pos_v.reshape(b, n, n) / (n - 1)
        return torch.stack([u * 2.0 - 1.0, v * 2.0 - 1.0], dim=-1)

    def inverse_at(self, points: torch.Tensor, code: torch.Tensor | None = None,
                   reference: torch.Tensor | None = None) -> torch.Tensor:
        """Exact inverse at **arbitrary** points ``(..., M, 2)``.

        :meth:`inverse` inverts the chart on a square grid, which is what a grid
        code needs.  An adaptive solver needs more: given a physical point, which
        chart cell contains it?  This method answers that question in closed
        form -- two monotone 1-D inversions per layer, no iteration -- by using
        the *same* knots as the forward map.  The result is the chart coordinate
        in ``[-1, 1]^2`` up to floating point, for any number of points.
        """
        if points.dim() < 2 or points.shape[-1] != 2:
            raise ValueError("points must have shape (..., M, 2)")
        m = points.shape[-2]
        lead = points.shape[:-2]
        flat = points.reshape(-1, m, 2)
        if reference is None:
            reference = self._reference_grid(points.shape[-2], points.device, points.dtype)
        if reference.dim() == 4:
            reference = self._align(reference, code)
        for layer in reversed(range(self.n_layers)):
            g, h = self._knots(reference, code, layer)
            k = g.shape[-1]
            g2 = g.reshape(-1, k)
            h2 = h.reshape(-1, k, k)
            b = flat.shape[0]
            if g2.shape[0] not in (1, b):
                raise ValueError("batch mismatch between points and chart code")
            if g2.shape[0] == 1 and b > 1:
                g2 = g2.expand(b, k)
                h2 = h2.expand(b, k, k)
            flat = self._invert_layer_points((g2, h2), flat)
        return flat.reshape(*lead, m, 2)

    @staticmethod
    def _invert_layer_points(knots: tuple[torch.Tensor, torch.Tensor],
                             points: torch.Tensor) -> torch.Tensor:
        """Invert one layer at ``(B, M, 2)`` arbitrary points."""
        g, h = knots
        b, k = g.shape[0], g.shape[-1]
        y1 = (points[..., 0] + 1.0) * 0.5
        y2 = (points[..., 1] + 1.0) * 0.5
        m = points.shape[-2]

        pos_u, _ = invert_monotone_1d(g, y1.reshape(b, -1))           # (B, M)
        i = pos_u.floor().clamp(0, k - 2).long()
        t = (pos_u - i.to(pos_u.dtype)).unsqueeze(-1)
        h_flat = h.reshape(b, k, k)
        idx = i.reshape(b, -1, 1).expand(b, m, k)
        h_lo = torch.gather(h_flat, 1, idx)
        h_hi = torch.gather(h_flat, 1, torch.clamp(idx + 1, max=k - 1))
        h_row = h_lo * (1.0 - t.reshape(b, -1, 1)) + h_hi * t.reshape(b, -1, 1)

        pos_v, _ = invert_monotone_1d(h_row.reshape(b * m, k), y2.reshape(b * m, 1))
        u = pos_u.reshape(b, m) / (k - 1)
        v = pos_v.reshape(b, m) / (k - 1)
        return torch.stack([u * 2.0 - 1.0, v * 2.0 - 1.0], dim=-1)

    @staticmethod
    def _reference_grid(n: int, device, dtype) -> torch.Tensor:
        t = torch.linspace(-1.0, 1.0, n, device=device, dtype=dtype)
        return torch.stack(torch.meshgrid(t, t, indexing="ij"), dim=-1)

    # ------------------------------------------------------------------ #
    # Certificates and diagnostics
    # ------------------------------------------------------------------ #
    def certified_det_lower_bound(self, coords: torch.Tensor,
                                  code: torch.Tensor | None = None) -> torch.Tensor:
        r"""Provable lower bound on :math:`\det J_\Phi` over the **whole square**.

        On a cell the two diagonal entries of :math:`J_\Phi` are

        .. math::
            \partial_1\Phi_1 = 2\Delta g_i/\Delta\xi, \qquad
            \partial_2\Phi_2 = 2\big[(1-t)\Delta_v h_{ij} + t\,\Delta_v h_{i+1,j}\big]/\Delta\xi
            \;\ge\; 2\min_{i,j}\Delta_v h_{ij}/\Delta\xi ,

        so

        .. math::
            \det J_\Phi \;\ge\;
            \Big(\frac{2\min_i \Delta g_i}{\Delta\xi}\Big)
            \Big(\frac{2\min_{ij} \Delta_v h_{ij}}{\Delta\xi}\Big) > 0

        at **every** point of the square, for **every** parameter value and
        **every** input.  With ``min_increment = eps > 0`` the right-hand side is
        at least :math:`(2\varepsilon/(K\Delta\xi))^2`, which does not depend on
        the parameters: the guarantee cannot be lost by training.

        Returns one value per batch element.
        """
        bound = None
        for layer in range(self.n_layers):
            g, h = self._knots(coords, code, layer)
            n = g.shape[-1]
            h_phys = 2.0 / (n - 1)
            dg = torch.diff(g, dim=-1).amin(dim=-1)
            dh = torch.diff(h, dim=-1).amin(dim=(-2, -1))
            layer_bound = (2.0 * dg / h_phys) * (2.0 * dh / h_phys)
            bound = layer_bound if bound is None else bound * layer_bound
        return bound

    def parameter_free_det_floor(self, n: int) -> float:
        r"""The bound :math:`\det J \ge (2\varepsilon/(K\Delta\xi))^{2 \times layers}` -- independent of the parameters."""
        if self.min_increment <= 0:
            return 0.0
        k = max(n - 1, 1)
        h_phys = 2.0 / max(n - 1, 1)
        return float(((2.0 * self.min_increment / k) / h_phys) ** (2 * self.n_layers))

    def det_jacobian(self, coords: torch.Tensor, code: torch.Tensor | None = None) -> torch.Tensor:
        """Analytic Jacobian determinant of the chart at ``coords``."""
        return self(coords, code)[1]

    def increments(self, coords: torch.Tensor, code: torch.Tensor | None = None
                   ) -> tuple[torch.Tensor, torch.Tensor]:
        """Row and column increments of the last layer (the actual cell sizes)."""
        g, h = self._knots(coords, code, self.n_layers - 1)
        return torch.diff(g, dim=-1), torch.diff(h, dim=-1)

    def inverse_consistency_error(self, coords: torch.Tensor,
                                  code: torch.Tensor | None = None) -> float:
        """``max |Phi^{-1}(Phi(x)) - x|`` over the reference nodes (must be ~0).

        The exact inverse is exact in exact arithmetic; in float32 the error grows
        with the condition number of the chart, i.e. with ``1 / min det J``.  For
        a trained chart (``min det J`` in ``[0.2, 5]``) it is below ``1e-5``; a
        chart that compresses area by ``1e6`` loses the information in the
        representation itself, which no inverse can recover.
        """
        if code is None and self.latent_dim > 0:
            code = torch.zeros(1, self.latent_dim, device=coords.device, dtype=coords.dtype)
        phi, _ = self(coords, code)
        back = self.inverse(phi, code, reference=coords)
        ref = coords if coords.dim() == 4 else coords.expand_as(back)
        return float((back - ref).abs().max())

    def extra_repr(self) -> str:  # pragma: no cover - cosmetic
        return (f"hidden={self.hidden}, n_layers={self.n_layers}, "
                f"latent_dim={self.latent_dim}, n_fourier={self.n_fourier}")


def chart_det_consistency(chart: DagneseTriangularChart, coords: torch.Tensor,
                          code: torch.Tensor | None = None) -> float:
    """``max |det J (analytic) - det J (finite differences)|`` over the grid."""
    phi, det = chart(coords, code)
    h = 2.0 / (coords.shape[-2] - 1)
    return float((det - jacobian_det(phi, spacing=h)).abs().max())
